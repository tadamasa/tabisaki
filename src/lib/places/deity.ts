const CANON = new Map(ALIASES.flatMap((names) => names.map((n) => [n, names[0]] as const)));

// 敬称や「命・尊・神」などの語尾を落として、比べられる形にする
export function normalizeDeity(raw: string) {
  const s = raw
    .replace(/[（(].*?[)）]/g, "")
    .replace(/\s/g, "")
    .replace(/^(主祭神|配祀神|祭神)[:：]?/, "")
    .replace(/(之命|命|尊|大神|大明神|之神|ノ神|神|公|天皇)$/u, (m) => (m === "天皇" ? "天皇" : ""));
  return CANON.get(s) ?? s;
}

// 基礎情報の「主祭神」（なければ「祭神」）の欄から神名を取り出す
export function parseDeities(wikitext: string): string[] {
  const field = (name: string) => {
    const m = wikitext.match(new RegExp(`^\\|\\s*${name}\\s*=\\s*(.+)$`, "m"));
    return m?.[1]?.trim() ?? "";
  };
  const value = field("主祭神") || field("祭神");
  if (!value) return [];
  const cleaned = value
    .replace(/<ref[^>]*\/>/g, "")
    .replace(/<ref[^>]*>[\s\S]*?<\/ref>/g, "")
    .replace(/\{\{[^}]*\}\}/g, "")
    .replace(/\[\[(?:[^|\]]*\|)?([^\]]*)\]\]/g, "$1")
    .replace(/'''?/g, "");
  const names = cleaned
    .split(/<br\s*\/?>|[、・，,／/]|\s+/)
    .map((n) => n.trim())
    .filter((n) => n && n.length <= 20 && !/ほか|他|など|等|柱$/.test(n));
  return [...new Set(names)].slice(0, 8);
}
